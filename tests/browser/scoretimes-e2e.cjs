const { chromium } = require('playwright');
const FX = process.argv[2], OUT = process.argv[3];
(async () => {
  const b = await chromium.launch();
  const page = await b.newPage({ viewport: { width: 1024, height: 1366 } });
  const errs = []; page.on('pageerror', e => errs.push(e.message));
  page.on('dialog', d => { console.log('dialog:', d.message()); d.accept(); });
  await page.goto('http://localhost:8765/');
  await page.evaluate(() => localStorage.setItem('myParts', '["Soprano 2"]'));
  await page.goto('http://localhost:8765/#/songs');
  await page.fill('input[placeholder^="New song"]', 'Let River Run');
  await page.click('text=+ Add');
  await page.waitForSelector('text=📄 Scores');
  await page.setInputFiles('input[accept^="application/pdf"]', FX + '/stamped.pdf');
  await page.waitForSelector('text=📖 Score');
  await page.setInputFiles('input[accept^="audio"]', [FX + '/River_Full.mp3']);
  await page.waitForTimeout(600);
  await page.click('.tabbar >> text=Rehearsal');
  await page.click('text=Start a new rehearsal');
  await page.click('label:has-text("Let River Run")');
  await page.click('text=Start rehearsal');
  await page.waitForSelector('text=Use the times printed on the score');
  await page.click('text=Use the times printed on the score');
  await page.waitForSelector('.modal');
  console.log('modal:', (await page.textContent('.modal')).slice(0, 220));
  await page.screenshot({ path: OUT + '/st1-modal.png' });
  await page.click('.modal button.primary');
  await page.waitForTimeout(500);
  console.log('start buttons:', await page.locator('.play-panel .start-btn').allTextContents());
  await page.click('.start-btn.letter:has-text("B")');
  await page.waitForTimeout(300);
  console.log('last:', (await page.locator('.bubble').allTextContents()).slice(-1)[0]);
  await page.screenshot({ path: OUT + '/st2-play.png' });
  console.log('errors:', errs.length ? errs : 'none');
  await b.close();
})();
