const { chromium } = require('playwright');
const FX = process.argv[2], OUT = process.argv[3];
(async () => {
  const b = await chromium.launch();
  const page = await b.newPage({ viewport: { width: 1024, height: 1366 } });
  const errs = []; page.on('pageerror', e => errs.push(e.message));
  page.on('dialog', d => d.accept());
  await page.goto('http://localhost:8765/');
  await page.waitForSelector('text=Which part(s) do you lead?');
  await page.screenshot({ path: OUT + '/p1-home.png' });
  await page.click('.setup .track-btn:has-text("Alto 1")');
  await page.click('.setup .track-btn:has-text("Alto 2")');
  await page.click('.setup >> text=Save');
  await page.waitForTimeout(300);
  console.log('setup card gone:', !(await page.isVisible('text=Which part(s) do you lead?')));
  await page.click('.tabbar >> text=Songs');
  await page.fill('input[placeholder^="New song"]', 'Let the River Run');
  await page.click('text=+ Add');
  await page.waitForSelector('text=📄 Scores');
  await page.setInputFiles('input[accept^="audio"]', [FX + '/River_Full.mp3', FX + '/River_Alto1.mp3', FX + '/River_Alto2.mp3']);
  await page.waitForTimeout(800);
  console.log('song page tracks:', await page.locator('.item-row .item-title').allTextContents());

  console.log('parts:', await page.locator('.part-select').evaluateAll(els => els.map(e => e.value || 'everyone')));
  await page.click('.tabbar >> text=Rehearsal');
  await page.click('text=Start a new rehearsal');
  console.log('title before:', await page.inputValue('input[aria-label="Rehearsal name"]'));
  await page.click('label:has-text("Let the River Run")');
  await page.click('text=Start rehearsal');
  console.log('blocked without part:', await page.isVisible('text=Which part?'));
  await page.click('.track-btn:has-text("Alto 1")');
  console.log('title after:', await page.inputValue('input[aria-label="Rehearsal name"]'));
  await page.screenshot({ path: OUT + '/p5-new.png' });
  await page.click('text=Start rehearsal');
  await page.waitForSelector('.play-panel .track-btn');
  await page.waitForTimeout(400);
  console.log('rehearsal tracks:', await page.locator('.play-panel .track-btn').allTextContents());
  await page.click('text=Show all parts');
  await page.waitForTimeout(400);
  console.log('after show all:', await page.locator('.play-panel .track-btn').allTextContents());
  await page.click('text=Show only my parts');
  await page.waitForTimeout(400);
  await page.screenshot({ path: OUT + '/p3-rehearsal.png' });
  await page.click('.tabbar >> text=Help');
  await page.waitForTimeout(300);
  await page.screenshot({ path: OUT + '/p4-help.png', fullPage: true });
  console.log('errors:', errs.length ? errs : 'none');
  await b.close();
})();
